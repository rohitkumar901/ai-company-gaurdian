import io
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
import pandas as pd

def export_events_to_csv(events: List[Dict[str, Any]]) -> str:
    """Convert events list to CSV string."""
    if not events:
        return ""
    df = pd.DataFrame(events)
    # Remove internal IDs or hashes from export if desired, or keep all
    columns_to_export = [c for c in df.columns if c not in ("event_hash", "import_job_id")]
    return df[columns_to_export].to_csv(index=False)

def export_alerts_to_csv(alerts: List[Dict[str, Any]]) -> str:
    """Convert alerts list to CSV string."""
    if not alerts:
        return ""
    df = pd.DataFrame(alerts)
    return df.to_csv(index=False)

def generate_executive_summary_report(
    kpis: Dict[str, Any],
    alerts: List[Dict[str, Any]],
    ml_metrics: Optional[Dict[str, Any]] = None,
    generated_by: str = "SOC Analyst"
) -> str:
    """Produce a formal markdown security summary report for stakeholders."""
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # Aggregate alert statistics
    total_alerts = len(alerts)
    crit_count = sum(1 for a in alerts if a.get("severity") == "CRITICAL")
    high_count = sum(1 for a in alerts if a.get("severity") == "HIGH")
    med_count = sum(1 for a in alerts if a.get("severity") == "MEDIUM")
    low_count = sum(1 for a in alerts if a.get("severity") == "LOW")

    # Most targeted users
    user_counts: Dict[str, int] = {}
    for a in alerts:
        u = a.get("username", "Unknown")
        user_counts[u] = user_counts.get(u, 0) + 1
    top_users = sorted(user_counts.items(), key=lambda x: x[1], reverse=True)[:5]
    top_users_str = "\n".join([f"- **{u}**: {cnt} alert(s)" for u, cnt in top_users]) or "- None"

    ml_section = ""
    if ml_metrics:
        ml_section = f"""
### 3. Machine Learning Anomaly Detection Evaluation
- **Model Architecture**: Isolation Forest (Unsupervised)
- **Precision**: {ml_metrics.get('precision', 'N/A')}
- **Recall**: {ml_metrics.get('recall', 'N/A')}
- **F1 Score**: {ml_metrics.get('f1_score', 'N/A')}
- **False Positive Rate (FPR)**: {ml_metrics.get('false_positive_rate', 'N/A')}
- **Evaluation Threshold**: {ml_metrics.get('threshold_used', 'N/A')}
"""

    report = f"""# AI Company Guardian — Security & Authentication Audit Report
**Generated On:** {now_str}  
**Generated By:** {generated_by}  
**System Version:** 1.0.0-PROTOTYPE

---

## Executive Summary
This document outlines the authentication telemetry and security anomalies detected by the AI Company Guardian platform. 
*Important Notice:* Flagged events represent suspected anomalies and policy deviations queued for triage. They should be verified by a security analyst prior to taking blocking operational actions.

---

## 1. Authentication Telemetry Overview
- **Total Ingested Events:** {kpis.get('total_events', 0):,}
- **Successful Logins:** {kpis.get('success_events', 0):,}
- **Failed Logins:** {kpis.get('failed_events', 0):,}
- **Unique Suspicious Events Flagged:** {kpis.get('suspicious_events', 0):,}
- **Open / Active Incidents:** {kpis.get('open_alerts', 0):,}
- **Resolved / Closed Incidents:** {kpis.get('closed_alerts', 0):,}

---

## 2. Alert Severity Breakdown
- **CRITICAL:** {crit_count}
- **HIGH:** {high_count}
- **MEDIUM:** {med_count}
- **LOW:** {low_count}
- **Total Alerts:** {total_alerts}

### Most Targeted User Accounts
{top_users_str}

---
{ml_section}

## 4. Recommendations & Next Steps
1. Enforce Multi-Factor Authentication (MFA) on accounts exhibiting repeated brute-force burst patterns.
2. Review IP ranges associated with distributed password-spraying attempts and consider geo-blocking or rate-limiting at the reverse proxy layer.
3. Validate off-hours logins with employees to confirm legitimate emergency or remote work scenarios.
4. Continue periodic retraining of the Isolation Forest baseline on confirmed benign logs.

---
*Report end.*
"""
    return report
