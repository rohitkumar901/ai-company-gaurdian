import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import Dict, Any
from database.queries import get_all_settings, log_audit_event

def send_alert_notification(alert: Dict[str, Any], operator_username: str = "SYSTEM") -> Dict[str, Any]:
    """
    Dispatches alert notification. Supports real SMTP if configured,
    or runs in simulated audit mode if SMTP is disabled.
    """
    settings = get_all_settings()
    smtp_enabled = settings.get("smtp_enabled", "False").lower() in ("true", "1", "yes")

    subject = f"[GUARDIAN ALERT - {alert.get('severity', 'HIGH')}] {alert.get('detection_rule')} for {alert.get('username')}"
    body = f"""
AI Company Guardian - Security Incident Notification
------------------------------------------------------
Alert ID:         {alert.get('alert_id')}
Timestamp:        {alert.get('created_at')}
Target Username:  {alert.get('username')}
Severity:         {alert.get('severity')}
Detection Method: {alert.get('detection_method')}
Triggered Rule:   {alert.get('detection_rule')}
Reason:           {alert.get('reason')}

Investigation Status: {alert.get('status', 'New')}
Action Required: Please review this alert in the AI Company Guardian SOC console.
------------------------------------------------------
This is an automated notification generated by AI Company Guardian.
"""

    if not smtp_enabled:
        # Simulated mode: Log to audit history
        log_audit_event(
            operator_username,
            "NOTIFICATION_SIMULATED",
            str(alert.get("alert_id")),
            f"Simulated email sent for alert {alert.get('alert_id')} (Severity: {alert.get('severity')})"
        )
        return {
            "status": "simulated",
            "message": "SMTP disabled. Notification simulated and recorded in audit log."
        }

    # Real SMTP Dispatch
    try:
        server_host = settings.get("smtp_server", "localhost")
        server_port = int(settings.get("smtp_port", "587"))
        sender_email = settings.get("smtp_sender", "alerts@company.internal")
        recipient_email = settings.get("smtp_recipient", "soc@company.internal")
        username = settings.get("smtp_username", "")
        password = settings.get("smtp_password", "")

        msg = MIMEMultipart()
        msg["From"] = sender_email
        msg["To"] = recipient_email
        msg["Subject"] = subject
        msg.attach(MIMEText(body, "plain"))

        with smtplib.SMTP(server_host, server_port, timeout=10) as server:
            server.starttls()
            if username and password:
                server.login(username, password)
            server.send_message(msg)

        log_audit_event(
            operator_username,
            "NOTIFICATION_SENT",
            str(alert.get("alert_id")),
            f"Email dispatched to {recipient_email} for alert {alert.get('alert_id')}"
        )
        return {"status": "success", "message": f"Alert email delivered to {recipient_email}"}

    except Exception as e:
        log_audit_event(
            operator_username,
            "NOTIFICATION_FAILED",
            str(alert.get("alert_id")),
            f"Failed to dispatch email: {str(e)}"
        )
        return {"status": "error", "message": f"Failed to send email: {str(e)}"}
